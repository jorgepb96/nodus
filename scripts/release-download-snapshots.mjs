// Dated history of GitHub release download counts.
//
// GitHub only reports a running total per uploaded file, with no dates and no
// origin, so a jump in the README counters cannot be traced back once it has
// happened. After every website deploy (the twice-daily refresh and every site
// push) the "Download stats" workflow records the count of every file of every
// published release in one table on the `download-stats` branch. Each change is
// one commit, so the branch history is the time series: the commit date says
// when, and the diff says which file grew and by how much. Updater manifests
// (latest*.yml) are kept on purpose: they count update checks by installed apps,
// which tells real use apart from downloads that never open the app.
//
// The branch never touches main, so it does not bypass the CLA gate there.

export const STATS_BRANCH = 'download-stats';
export const STATS_FILE = 'downloads.tsv';

const HEADER = 'tag\tpublished\tasset\tdownloads';

const README = `# Nodus release download history

Generated by \`.github/workflows/download-stats.yml\` after every website deploy.
Do not edit by hand.

\`${STATS_FILE}\` holds the download count of every file of every published
release at the moment in its \`# taken\` line. Each commit that changes it is
one snapshot, so \`git log -p -- ${STATS_FILE}\` shows when each count grew.
\`node scripts/release-download-history.mjs\` on main prints the increase of
every file between consecutive snapshots.
`;

// Code-point order, so the table and its diffs are identical on every machine.
const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function clean(value) {
  return String(value ?? '').replace(/[\t\r\n]+/g, ' ');
}

/** One row per uploaded file of every published release, newest release first. */
export function downloadRows(releases) {
  const rows = [];
  const published = (Array.isArray(releases) ? releases : [])
    .filter((release) => release && !release.draft && typeof release.tag_name === 'string')
    .sort((a, b) => byCode(String(b.published_at ?? ''), String(a.published_at ?? '')) || byCode(a.tag_name, b.tag_name));
  for (const release of published) {
    const assets = (Array.isArray(release.assets) ? release.assets : [])
      .filter((asset) => typeof asset?.name === 'string' && Number.isFinite(Number(asset.download_count)))
      .sort((a, b) => byCode(a.name, b.name));
    for (const asset of assets) {
      rows.push([clean(release.tag_name), clean(release.published_at), clean(asset.name), String(Number(asset.download_count))].join('\t'));
    }
  }
  return rows;
}

export function formatDownloadTable(releases, takenAt) {
  return [
    '# Nodus release asset downloads, one row per uploaded file.',
    `# taken\t${takenAt}`,
    HEADER,
    ...downloadRows(releases),
  ].join('\n') + '\n';
}

/** The counts of a table, keyed by tag and file name. */
export function parseDownloadTable(text) {
  const counts = new Map();
  let takenAt = null;
  for (const line of String(text ?? '').split('\n')) {
    if (line.startsWith('# taken\t')) { takenAt = line.slice('# taken\t'.length); continue; }
    if (!line || line.startsWith('#') || line === HEADER) continue;
    const [tag, , asset, downloads] = line.split('\t');
    if (tag && asset && downloads !== undefined) counts.set(`${tag}\t${asset}`, Number(downloads));
  }
  return { takenAt, counts };
}

/** Files whose count grew (or appeared) between two tables, largest increase first. */
export function downloadIncreases(previousText, nextText) {
  const before = parseDownloadTable(previousText).counts;
  const after = parseDownloadTable(nextText).counts;
  const increases = [];
  for (const [key, count] of after) {
    const delta = count - (before.get(key) ?? 0);
    if (delta > 0) {
      const [tag, asset] = key.split('\t');
      increases.push({ tag, asset, delta, count });
    }
  }
  return increases.sort((a, b) => b.delta - a.delta || byCode(a.tag, b.tag) || byCode(a.asset, b.asset));
}

function sameCounts(a, b) {
  const left = parseDownloadTable(a).counts;
  const right = parseDownloadTable(b).counts;
  if (left.size !== right.size) return false;
  for (const [key, count] of left) if (right.get(key) !== count) return false;
  return true;
}

async function ensureStatsBranch(github, repo) {
  try {
    await github.rest.git.getRef({ ...repo, ref: `heads/${STATS_BRANCH}` });
    return;
  } catch (error) {
    if (error.status !== 404) throw error;
  }
  // An orphan branch: it shares no history with main and carries only the data.
  const { data: tree } = await github.rest.git.createTree({
    ...repo, tree: [{ path: 'README.md', mode: '100644', type: 'blob', content: README }],
  });
  const { data: commit } = await github.rest.git.createCommit({
    ...repo, message: 'Start the release download history', tree: tree.sha, parents: [],
  });
  await github.rest.git.createRef({ ...repo, ref: `refs/heads/${STATS_BRANCH}`, sha: commit.sha });
}

async function readCurrentTable(github, repo) {
  try {
    const { data } = await github.rest.repos.getContent({ ...repo, path: STATS_FILE, ref: STATS_BRANCH });
    return { sha: data.sha, text: Buffer.from(data.content, 'base64').toString('utf8') };
  } catch (error) {
    if (error.status !== 404) throw error;
    return { sha: undefined, text: '' };
  }
}

export async function recordDownloadSnapshot({ github, context, core, now = () => new Date() }) {
  const repo = { owner: context.repo.owner, repo: context.repo.repo };
  const releases = await github.paginate(github.rest.repos.listReleases, { ...repo, per_page: 100 });
  const takenAt = now().toISOString();
  const next = formatDownloadTable(releases, takenAt);

  await ensureStatsBranch(github, repo);
  const current = await readCurrentTable(github, repo);
  if (current.text && sameCounts(current.text, next)) {
    core.info(`No download count changed since ${parseDownloadTable(current.text).takenAt}; nothing recorded.`);
    return { recorded: false, increases: [] };
  }

  const increases = current.text ? downloadIncreases(current.text, next) : [];
  const added = increases.reduce((sum, item) => sum + item.delta, 0);
  await github.rest.repos.createOrUpdateFileContents({
    ...repo,
    branch: STATS_BRANCH,
    path: STATS_FILE,
    message: current.text ? `Release downloads at ${takenAt} (+${added})` : `Release downloads at ${takenAt}`,
    content: Buffer.from(next, 'utf8').toString('base64'),
    ...(current.sha ? { sha: current.sha } : {}),
  });
  for (const item of increases.slice(0, 15)) core.info(`+${item.delta}\t${item.tag}\t${item.asset}`);
  core.info(`Recorded ${parseDownloadTable(next).counts.size} release files at ${takenAt}.`);
  return { recorded: true, increases };
}
