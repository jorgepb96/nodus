import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {installRuntimeHooks,requireElectronRuntime} from './lib/tsRuntimeHooks.mjs';
if(!requireElectronRuntime(fileURLToPath(import.meta.url),'--electron-mobile-database-publication'))process.exit(0);
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'nodus-mobile-database-publication-'));
const runtime=installRuntimeHooks(directory);runtime.app.on=()=>{};runtime.app.once=()=>{};
const require=createRequire(import.meta.url),originalFetch=globalThis.fetch;
globalThis.fetch=async()=>{throw new Error('Publishing an autonomous report must never invoke a provider');};
let database;
try {
  database=require('../electron/db/database.ts');database.getDb();
  const vaults=require('../electron/vaults/vaultRegistry.ts'),vault=vaults.createVault('Datos aislados','databases'),other=vaults.createVault('Otros datos','databases');
  const api=require('../electron/desktopBridge/databaseResearchPublication.ts'),reading=require('../electron/desktopBridge/databaseResearchReading.ts');
  const repo=require('../electron/db/databasesRepo.ts'),reports=require('../electron/db/databaseDeepResearchRepo.ts');
  const engine=require('../shared/databaseResearchEngine.ts'),mobile=require('../shared/mobileDatabaseResearch.ts');
  const boundary=require('../electron/desktopBridge/executionBoundary.ts');
  const inVault=(id,work)=>vaults.withOwningVault(id,()=>database.withVaultDatabase(id,work));
  await inVault(vault.id,async()=>{
    const source=repo.createDatabase('Datos de prueba'),column=repo.createColumn(source.id,'Métrica','number');
    for(let i=0;i<20;i++){const row=repo.createRow(source.id);repo.setCell(row.id,column.id,String(i+1));}
    const view=repo.createView(source.id,{name:'Mayores descendentes',layout:'table',config:{filter:{type:'condition',columnId:column.id,op:'gte',value:'10'},sorts:[{columnId:column.id,dir:'desc'}]}});
    const pack=api.mobileDatabaseResearchSourcePack({databaseIds:[source.id]});
    assert.equal(pack.databases[0].snapshot.rows.length,20);assert.equal(pack.databases[0].viewRows[view.id].length,11);
    const sources=mobile.mobileDatabaseSources([pack],[source.id]);
    const analyze=async(...args)=>engine.runDatabaseDeepResearch(...args),host=mobile.mobileDatabaseResearchHost({},sources,analyze);
    const local=host.captureSnapshot(source.id,{maxRows:7},undefined,{viewId:view.id});
    const native=require('../electron/ai/databaseDeepResearch.ts').captureDatabaseResearchSnapshot(source.id,{maxRows:7},undefined,{viewId:view.id});
    assert.equal(local.hash,native.hash,'Saved filters, sorting and truncation retain the exact SQLite snapshot');
    const request={databaseIds:[source.id],viewIds:[view.id],objective:'Describir la métrica verificable',depth:'focused',language:'es',reportType:'general',autoConfigure:false,model:{provider:'openai',model:'fixture'},filters:{query:'',columnIds:[]},roles:{},planSections:[]};
    const requestId=randomUUID(),memory=new mobile.MobileDatabaseResearchRepository(mobile.createMobileDatabaseResearchDetail(`dbr_mobile_${requestId}`,request,sources));
    const detail=await engine.processDatabaseResearchRun(memory.detail.run.id,{},mobile.mobileDatabaseResearchHost(memory,sources,analyze));
    const raw=JSON.parse(JSON.stringify({request,sourcePacks:[pack],detail,requestId}));
    assert(detail.report,'Actual shared numerical pipeline produced a complete report');
    const saved=await api.saveMobileDatabaseResearchReport(raw,analyze);
    const {updatedAt:_updated,readAt:_read,...deviceSource}=raw.detail.report;
    assert.equal(saved.id,raw.detail.report.id);assert.equal(saved.runId,raw.detail.run.id);
    assert.equal(reading.mobileDatabaseResearchReader(saved.id).sourceRevision,engine.sha256Snapshot(deviceSource),'Publication preserves local annotation anchors exactly');
    database.getDb().prepare('UPDATE database_research_reports SET read_at=? WHERE id=?').run('2026-10-11T01:00:00Z',saved.id);
    const replay=await api.saveMobileDatabaseResearchReport(raw,()=>{throw new Error('Lost ACK cannot recompute an acknowledged report');});
    assert.equal(replay.readAt,'2026-10-11T01:00:00Z');
    assert.equal(database.getDb().prepare('SELECT COUNT(*) AS n FROM database_research_runs').get().n,1);
    await assert.rejects(api.saveMobileDatabaseResearchReport({...raw,detail:{...raw.detail,report:{...raw.detail.report,markdown:'Alterado'}}},analyze),/idempotency_conflict/);
    await assert.rejects(boundary.withMobileOperation(()=>api.saveMobileDatabaseResearchReport(raw,analyze),['corpus']),/operation_forbidden/);
    const replaceIdentity=value=>{const copy=structuredClone(value),id=randomUUID();copy.requestId=id;copy.detail.run.id=`dbr_mobile_${id}`;copy.detail.report.id=`dbr_report_dbr_mobile_${id}`;copy.detail.report.runId=copy.detail.run.id;return copy;};
    const forged=replaceIdentity(raw);forged.sourcePacks[0].signature='0'.repeat(64);
    await assert.rejects(api.saveMobileDatabaseResearchReport(forged,analyze),/signature_invalid/);
    const manipulated=replaceIdentity(raw);manipulated.sourcePacks[0].databases[0].snapshot.rows[0].cells[column.id]='999';
    await assert.rejects(api.saveMobileDatabaseResearchReport(manipulated,analyze),/source_pack/);
    const unsupported=replaceIdentity(raw);unsupported.detail.report.markdown+='\nCifra inventada: 999999.';
    await assert.rejects(api.saveMobileDatabaseResearchReport(unsupported,analyze),/verification_failed/);
    assert.equal(database.getDb().prepare('SELECT COUNT(*) AS n FROM database_research_runs').get().n,1,'Invalid publications leave no half-created runs');
    await inVault(other.id,async()=>{await assert.rejects(api.saveMobileDatabaseResearchReport(replaceIdentity(raw),analyze),/signature_invalid/);});
    reports.deleteDatabaseResearchReport(saved.id);
    await assert.rejects(api.saveMobileDatabaseResearchReport(raw,analyze),/result_unavailable/);
  });
  console.log('Signed complete sources, exact saved views, deterministic verification, real SQLite persistence, stable annotations, receipt replay, revocation and atomic rejection passed. Device/network acceptance remains separate.');
} finally {
  globalThis.fetch=originalFetch;database?.closeDb();runtime.restore();fs.rmSync(directory,{recursive:true,force:true});
}
