import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import test from 'node:test';
import { build } from 'esbuild';
const root = await mkdtemp(path.join(os.tmpdir(), 'nodus-reranking-test-'));
const entry = path.resolve('electron/ai/documentaryReranking.ts');
await build({ entryPoints: [entry, path.resolve('electron/db/documentaryRetrieval.ts'), path.resolve('shared/embeddingComparison.ts'), path.resolve('shared/embeddingInputProfiles.ts')], outdir: root, outbase: path.resolve('.'), bundle: true, platform: 'node', format: 'esm', outExtension: { '.js': '.mjs' }, alias: { '@shared': path.resolve('shared') }, logLevel: 'silent' });
const { rerankDocumentaryCandidates } = await import(pathToFileURL(path.join(root, 'electron/ai/documentaryReranking.mjs')));
const { runDocumentaryRetrieval } = await import(pathToFileURL(path.join(root, 'electron/db/documentaryRetrieval.mjs')));
const { retrievalQuality } = await import(pathToFileURL(path.join(root, 'shared/embeddingComparison.mjs')));
const profiles = await import(pathToFileURL(path.join(root, 'shared/embeddingInputProfiles.mjs')));
test.after(() => rm(root, { recursive: true, force: true }));
const a = { id: 'a', document_id: 'doc-a', index_key: 'index-a', text: 'La reforma de una cocina no explica la ley de educación.', locator_json: '{}' };
const b = { id: 'b', document_id: 'doc-b', index_key: 'index-b', text: 'La reforma educativa de 1931 amplió la enseñanza pública.', locator_json: '{}' };
const settings = { preset: 'custom', candidates: 30, passagesPerRound: 1, evidenceTokens: 4000, rounds: 1, autoExpand: false, threshold: { mode: 'automatic' } };
const store = { lexicalSearch: () => [a, b], semanticSearch: () => [a, b], adjacentPassages: () => [], physicalPages: () => [] };
const input = { query: 'ley educativa 1931', lexicalKeys: ['index-a', 'index-b'], vectorKeys: ['index-a', 'index-b'], vector: [1, 0], threshold: -1, settings };
test('bounded reranking changes production selection before budgets and preserves original ordering when inputs change', async () => {
  const baseline = runDocumentaryRetrieval(store, { ...input, includeRerankCandidates: true });
  assert.equal(baseline.passages[0].id, 'a');
  const ranked = await rerankDocumentaryCandidates(input.query, baseline.rerankCandidates, async () => [0.1, 0.9]);
  assert.equal(ranked.state, 'applied');
  const next = runDocumentaryRetrieval(store, { ...input, rerankOrder: ranked.order });
  assert.equal(next.passages[0].id, 'b'); assert.equal(next.rerankingApplied, true);
  assert.equal(retrievalQuality(next.passages.map(hit => hit.id), { ids: ['b'], complete: true }, 1).ndcg, 1);
  const old = b.text; b.text = 'Texto modificado mientras se reordenaban los candidatos.';
  const stale = runDocumentaryRetrieval(store, { ...input, rerankOrder: ranked.order });
  assert.equal(stale.rerankingApplied, false); assert.equal(stale.passages[0].id, 'a'); b.text = old;
  const pool = Array.from({ length: 100 }, (_, i) => ({ ...a, id: String(i), text: 'a'.repeat(9000) }));
  await rerankDocumentaryCandidates('consulta', pool, async (_q, texts) => { assert.equal(texts.length, 30); assert.ok(texts.every(text => text.length <= 4000)); return texts.map((_, i) => i); });
});
test('unavailable, invalid and slow rerankers fall back; cancellation remains cancellation', async () => {
  assert.equal((await rerankDocumentaryCandidates('q', [a, b], async () => null)).state, 'unavailable');
  assert.equal((await rerankDocumentaryCandidates('q', [a, b], async () => [NaN, 1])).state, 'failed');
  assert.equal((await rerankDocumentaryCandidates('q', [a, b], async () => { throw new Error('offline'); })).state, 'failed');
  assert.equal((await rerankDocumentaryCandidates('q', [a, b], () => new Promise(() => {}), undefined, 10)).state, 'timeout');
  const controller = new AbortController();
  const pending = rerankDocumentaryCandidates('q', [a, b], () => new Promise(() => {}), controller.signal);
  const rejected = assert.rejects(pending, /cancelled/); controller.abort(new Error('cancelled')); await rejected;
});
test('quality requires complete annotations, penalizes missing hits and deduplicates results', () => {
  assert.equal(retrievalQuality(['a']), null);
  assert.equal(retrievalQuality(['a'], { ids: ['a'], complete: false }), null);
  assert.equal(retrievalQuality(['a', 'a'], { ids: ['a', 'b'], complete: true }, 2).recall, 0.5);
  assert.ok(retrievalQuality(['a'], { ids: ['a', 'b'], complete: true }, 2).ndcg < 1);
  assert.equal(retrievalQuality(['wrong', 'b'], { ids: ['b'], complete: true }, 2).mrr, 0.5);
});
test('input profiles detect supported recipes, validate overrides and preserve prefixes within input limits', () => {
  const e5 = profiles.defaultEmbeddingInputProfile('ollama', 'intfloat/multilingual-e5-large');
  assert.equal(profiles.embeddingInputText('ley educativa', 'query', e5), 'query: ley educativa');
  assert.equal(profiles.embeddingInputText('ley educativa', 'document', e5), 'passage: ley educativa');
  assert.equal(profiles.defaultEmbeddingInputProfile('ollama', 'nomic-embed-text').documentPrefix, 'search_document: ');
  assert.equal(profiles.defaultEmbeddingInputProfile('openrouter', 'multilingual-e5-large-instruct').kind, 'plain', 'instruct variants must not inherit another model\'s recipe');
  assert.equal(profiles.embeddingInputText('a'.repeat(9000), 'document', e5).length, 8000);
  assert.throws(() => profiles.validateEmbeddingInputProfile({ ...e5, queryPrefix: 'bad' }, 'ollama', 'e5'), /prefijos/);
});
