import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { installRuntimeHooks, requireElectronRuntime, repoRoot } from './lib/tsRuntimeHooks.mjs';
if (!requireElectronRuntime(fileURLToPath(import.meta.url), '--documentary-lifecycle')) process.exit(0);
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nodus-documentary-lifecycle-'));
installRuntimeHooks(root);
const require = createRequire(import.meta.url);
const load = file => require(path.join(repoRoot, file));
const registry = load('electron/vaults/vaultRegistry.ts');
const database = load('electron/db/database.ts');
const preparation = load('electron/ai/documentaryPreparation.ts');
const experience = load('electron/ai/researchPreparationExperience.ts');
const inventory = load('electron/ai/researchCorpusInventory.ts');
const owned = (vault, fn) => registry.withOwningVault(vault.id, () => database.withVaultDatabase(vault.id, fn));
const seed = (id, key = id) => database.getDb().prepare("INSERT INTO works(nodus_id,zotero_key,title,authors_json,item_type,source_type) VALUES(?,?,?,'[]','book','text')").run(id, key, id);
const poll = async fn => { for (let i = 0; i < 100; i++) { if (fn()) return; await new Promise(resolve => setTimeout(resolve, 50)); } assert.fail('Timed out waiting for automatic discovery'); };
try {
  const vault = registry.getActiveVault();
  const other = registry.createVault('Other academic', 'academic');
  const study = registry.createVault('Unchanged study', 'estudio');
  seed('old-pending');
  preparation.setResearchPreparationPaused(true);
  const store = preparation.documentaryStore();
  const repo = new (load('electron/db/documentaryCampaigns.ts').DocumentaryCampaigns)(store.db);
  repo.savePolicy({ ...repo.policy(vault.id), automaticVersion: undefined, futureAdditions: false });
  repo.savePolicy({ ...repo.policy(other.id), automaticVersion: undefined, decision: 'declined', futureAdditions: false });
  await preparation.initializeDocumentaryPreparation();
  assert.equal(experience.getResearchPreparationPolicy().futureAdditions, true, 'legacy default migrates to automatic future additions');
  assert.equal(repo.policy(other.id).futureAdditions, false, 'an explicit refusal stays off');
  assert.ok(repo.policy(vault.id).known.some(id => id.endsWith('old-pending')));
  preparation.notifyResearchCorpusChanged();
  await new Promise(resolve => setTimeout(resolve, 1200));
  assert.equal(repo.list().length, 0, 'old inventory is not silently queued');
  seed('new-one'); seed('new-two');
  await owned(study, () => seed('study-new'));
  preparation.notifyResearchCorpusChanged();
  await poll(() => repo.list().length === 1);
  const queued = experience.getResearchPreparationProgress().campaigns[0];
  assert.equal(queued.audit.reason, 'new_content');
  assert.deepEqual(queued.jobs.map(job => job.title).sort(), ['new-one', 'new-two']);
  assert.equal(queued.vaultId, vault.id);
  assert.ok(queued.jobs.every(job => job.state === 'queued'));
  assert.ok(!repo.list().some(campaign => campaign.vault_id === study.id), 'no non-academic preparation');
  experience.setResearchPreparationPolicy({ futureAdditions: false });
  seed('opted-out'); preparation.notifyResearchCorpusChanged();
  await new Promise(resolve => setTimeout(resolve, 1200));
  assert.equal(repo.list().length, 1);
  assert.ok(experience.getResearchPreparationProgress().campaigns[0].jobs.every(job => job.state === 'queued'), 'opt-out preserves queued work');
  // Shared identity: one publication, two academic vault owners.
  seed('shared-a', 'ABCDEFGH'); await owned(other, () => seed('shared-b', 'ABCDEFGH'));
  await preparation.reconcileResearchDocumentOwnership();
  const document = inventory.researchCorpusInventory().documents.find(doc => doc.workId === 'shared-a');
  const identity = { documentId: document.id, attachmentId: null, revision: document.revision, textFingerprint: 'fixture', chunkerVersion: '280-60/1', processingVersion: '1',
    embedding: { provider: 'fixture', model: 'fixture', dimensions: 2, metric: 'cosine', parameters: {} } };
  const key = store.enqueue(identity, {});
  store.setPreference('paused', false);
  const job = store.claim();
  store.setPreference('paused', true);
  store.saveExtraction(job, 'Unique deletion evidence');
  store.saveChunks(job, [{ text: 'Unique deletion evidence', pageLabel: null, pageNumber: null, sourceRef: null }]);
  store.publishLexical(job); store.publishEmbeddings(job, [[1, 0]]);
  store.publishDocument(document, [key]);
  new (load('electron/db/documentaryEmbeddingBatches.ts').DocumentaryEmbeddingBatches)(store.db);
  const operation = `embedding:${document.id}:fixture`;
  repo.requests.enqueue(operation, document.revision, operation);
  store.db.prepare('INSERT INTO documentary_embedding_chunks VALUES(?,0,?, ?,2)').run(operation, 'fixture', '[1,0]');
  const scope = { documents: [document] };
  database.getDb().prepare('DELETE FROM works WHERE nodus_id=?').run('shared-a');
  await preparation.reconcileResearchDocumentOwnership();
  assert.ok(store.revision(key), 'another vault keeps the shared index');
  assert.throws(() => load('electron/ai/researchCorpusScope.ts').assertResearchDocumentPermission(scope, document.id, { ...document, workId: null }), /not_authorized/, 'removal revokes old direct citations even when the canonical global document survives');
  await owned(other, () => database.getDb().prepare('DELETE FROM works WHERE nodus_id=?').run('shared-b'));
  await preparation.reconcileResearchDocumentOwnership();
  assert.equal(store.revision(key), null);
  assert.equal(store.db.prepare('SELECT COUNT(*) n FROM documentary_passages WHERE document_id=?').get(document.id).n, 0);
  assert.equal(store.lexicalSearch('Unique deletion', [key], 5).length, 0);
  assert.equal(store.db.prepare('SELECT COUNT(*) n FROM documentary_embedding_chunks WHERE operation=?').get(operation).n, 0, 'working vectors are deleted too');
  assert.equal(store.db.prepare('SELECT document_id FROM documentary_requests WHERE document_id=?').get(operation), undefined);
  assert.throws(() => store.publishEmbeddings(job, [[1, 0]]), /lease_lost/, 'deleted publication cannot be resurrected by a stale writer');
  experience.setResearchPreparationPolicy({ futureAdditions: true });
  const beforeReimport = repo.list().length;
  seed('shared-reimport', 'ABCDEFGH'); preparation.notifyResearchCorpusChanged();
  await poll(() => repo.list().length === beforeReimport + 1);
  assert.ok(experience.getResearchPreparationProgress().campaigns.some(campaign => campaign.jobs.some(job => job.title === 'shared-reimport')), 're-import after deletion is a new addition');
  console.log('Automatic academic-only discovery, opt-out, shared deletion and citation revocation passed.');
} finally { await preparation.closeDocumentaryPreparation(); database.closeDb(); fs.rmSync(root, { recursive: true, force: true }); }
