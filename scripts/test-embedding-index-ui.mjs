import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdtemp, readFile, rm, mkdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { build } from 'esbuild';
import { chromium } from 'playwright-core';
import { launchComponentBrowser } from './lib/component-test-browser.mjs';
import { componentStyles } from './lib/component-test-styles.mjs';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const chrome = [process.env.CHROME_BIN, '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].filter(Boolean).find(existsSync);
test('saved-index controls preserve the active index and deletion requires every confirmation', { timeout: 120_000 }, async t => {
  if (!chrome) { t.skip('An isolated test browser is required'); return; }
  const root = await mkdtemp(path.join(os.tmpdir(), 'nodus-embedding-ui-'));
  const { browser, close } = await launchComponentBrowser(chromium, { executablePath: chrome, headless: true });
  try {
    const bundle = await build({ entryPoints: [path.join(repo, 'scripts/fixtures/embedding-indexes/renderer.tsx')], bundle: true, write: false, outdir: root, platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, alias: { '@shared': path.join(repo, 'shared') } });
    const page = await browser.newPage({ viewport: { width: 1120, height: 900 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.setContent('<html class="dark"><body><div id="root"></div></body></html>');
    await page.addStyleTag({ content: await readFile(componentStyles(), 'utf8') });
    for (const file of bundle.outputFiles) { if (file.path.endsWith('.css')) await page.addStyleTag({ content: file.text }); else if (file.path.endsWith('.js')) await page.addScriptTag({ content: file.text }); }
    const manager = page.getByTestId('embedding-index-manager'); await page.getByTestId('embedding-index-b').waitFor();
    await page.getByTestId('embedding-index-a').getByText('38 reutilizados', { exact: false }).waitFor();
    const local = page.getByTestId('local-reranker-control');
    const rows = local.getByTestId('local-reranker-models').locator('article');
    assert.equal(await rows.count(), 3, 'three rerankers are offered');
    const bge = local.getByTestId('local-reranker-bge-reranker-v2-m3-q8_0'), gte = local.getByTestId('local-reranker-bge-reranker-v2-m3-q4_k_m');
    // An installed model is detected: no download offered, and it is the one in use.
    await bge.getByText('En uso', { exact: true }).waitFor();
    assert.equal(await bge.getByRole('button', { name: /Descargar/ }).count(), 0, 'an installed model is never offered for download again');
    await local.getByRole('checkbox').check();
    await page.waitForFunction(() => window.actions.some(action => action[0] === 'settings' && action[1].researchReranking === 'local'));
    await gte.getByRole('button', { name: 'Descargar (418 MB)', exact: true }).click();
    await gte.getByRole('button', { name: 'Usar este modelo', exact: true }).waitFor();
    assert.ok((await page.evaluate(() => window.actions)).some(action => action[0] === 'reranker' && action[1] === 'download' && action[2] === 'bge-reranker-v2-m3-q4_k_m'));
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'settings' && action[1].researchRerankerModel), false, 'a second download does not take over the selection');
    await gte.getByRole('button', { name: 'Usar este modelo', exact: true }).click();
    await gte.getByText('En uso', { exact: true }).waitFor();
    await page.waitForFunction(() => window.actions.some(action => action[0] === 'settings' && action[1].researchRerankerModel === 'bge-reranker-v2-m3-q4_k_m'));
    // Deletion asks first; cancelling keeps the files.
    await bge.getByRole('button', { name: 'Eliminar', exact: true }).click();
    const rerankerDialog = page.getByRole('dialog');
    await rerankerDialog.getByText(/BGE Reranker v2 M3 Q8_0/).waitFor();
    await rerankerDialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'rerankerDelete'), false);
    await bge.getByRole('button', { name: 'Eliminar', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Eliminar modelo', exact: true }).click();
    await bge.getByRole('button', { name: 'Descargar (606 MB)', exact: true }).waitFor();
    assert.ok((await page.evaluate(() => window.actions)).some(action => action[0] === 'rerankerDelete' && action[1] === 'bge-reranker-v2-m3-q8_0'));
    assert.equal(await local.getByRole('checkbox').isChecked(), true, 'deleting a model that is not in use keeps reranking on');
    await gte.getByRole('button', { name: 'Eliminar', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Eliminar modelo', exact: true }).click();
    await page.waitForFunction(() => window.actions.some(action => action[0] === 'settings' && action[1].researchReranking === 'off'));
    assert.equal(await local.getByRole('checkbox').isDisabled(), true, 'without the model in use, reranking is switched off visibly');
    const profile = page.getByTestId('embedding-input-profile'); await profile.locator('summary').click();
    await profile.getByRole('combobox').selectOption('e5');
    await profile.getByRole('button', { name: 'Preparar con este perfil', exact: true }).click();
    await page.getByRole('dialog').getByText('"query: "', { exact: true }).waitFor();
    await page.getByRole('dialog').getByText('"passage: "', { exact: true }).waitFor();
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'prepare'), false);
    await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
    const comparison = page.getByTestId('embedding-comparison'); await comparison.locator(':scope > summary').click();
    await comparison.getByRole('textbox', { name: 'Preguntas de prueba', exact: true }).fill('¿Qué cambió en la educación en 1931?');
    await comparison.getByRole('button', { name: 'Comparar', exact: true }).click();
    await page.getByTestId('comparison-arm-0').getByText('p. 12', { exact: false }).waitFor();
    await page.getByTestId('comparison-arm-1').getByText('Sin anotaciones completas: calidad no evaluada.', { exact: true }).waitFor();
    if (process.env.NODUS_EMBEDDING_UI_ARTIFACTS) {
      await mkdir(process.env.NODUS_EMBEDDING_UI_ARTIFACTS, { recursive: true });
      await page.getByTestId('comparison-arm-0').scrollIntoViewIfNeeded();
      await page.screenshot({ path: path.join(process.env.NODUS_EMBEDDING_UI_ARTIFACTS, 'embedding-comparison.png'), fullPage: true });
    }
    const exported = page.waitForEvent('download');
    await comparison.getByRole('button', { name: 'Exportar comparación', exact: true }).click();
    const download = await exported;
    const reportFile = path.join(root, 'comparison.json');
    await download.saveAs(reportFile);
    const result = JSON.parse(await readFile(reportFile, 'utf8'));
    assert.equal(result.format, 'nodus.embedding-comparison/1'); assert.equal(result.arms.length, 2);
    await comparison.getByText('Evaluar con anotaciones de relevancia', { exact: true }).click();
    await comparison.getByRole('textbox', { name: 'IDs pertinentes', exact: true }).fill('evidence-one');
    await comparison.getByRole('checkbox', { name: 'La lista de resultados pertinentes está completa', exact: true }).check();
    await comparison.getByRole('button', { name: 'Comparar', exact: true }).click();
    await page.getByTestId('comparison-arm-0').getByText('Hit@10: 1 · Recall@10: 100% · MRR: 1.000 · nDCG: 1.000', { exact: true }).waitFor();
    await page.evaluate(() => { window.holdComparisons = true; });
    await comparison.getByRole('button', { name: 'Comparar', exact: true }).click();
    await comparison.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.ok((await page.evaluate(() => window.actions)).some(action => action[0] === 'cancelComparison'));
    await page.evaluate(() => { window.holdComparisons = false; });
    await page.getByTestId('embedding-index-b').getByRole('button', { name: 'Actualizar y activar', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByText(/puede generar costes/).waitFor();
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'prepare'), false);
    await page.evaluate(() => window.rerender());
    await dialog.getByText('Excluido por el usuario', { exact: false }).waitFor();
    await dialog.getByRole('button', { name: 'Preparar y activar', exact: true }).click();
    await page.getByTestId('embedding-index-b').getByRole('button', { name: 'Pausar', exact: true }).waitFor();
    assert.match(await page.getByTestId('embedding-index-a').innerText(), /Activo/);
    await page.getByTestId('embedding-index-b').getByRole('button', { name: 'Pausar', exact: true }).click();
    await page.getByTestId('embedding-index-b').getByRole('button', { name: 'Reanudar', exact: true }).waitFor();
    await page.getByTestId('embedding-index-a').getByRole('button', { name: 'Eliminar', exact: true }).click();
    await dialog.getByText(/bóveda quedará sin índice/).waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Cancelar', exact: true }).evaluate(element => element === document.activeElement), true);
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    await dialog.getByRole('textbox').fill('wrong');
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    await dialog.getByText('El código no coincide.', { exact: true }).waitFor();
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'delete'), false);
    const code = await dialog.locator('p').filter({ hasText: /^\d{6}$/ }).innerText();
    await dialog.getByRole('textbox').fill(code);
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    await dialog.getByText(/Confirma la eliminación definitiva/).waitFor();
    assert.equal((await page.evaluate(() => window.actions)).some(action => action[0] === 'delete'), false);
    await dialog.getByRole('button', { name: 'Eliminar definitivamente', exact: true }).click();
    await manager.getByText(/Sin índice semántico activo/).waitFor();
    assert.ok((await page.evaluate(() => window.actions)).some(action => action[0] === 'delete' && action[1] === 'a'));
    // An index of a superseded mean-pooled profile keeps working and points to its CLS profile.
    await page.evaluate(() => window.addLegacyPoolingIndex());
    const superseded = page.getByTestId('embedding-index-c').getByTestId('embedding-index-superseded');
    await superseded.getByText(/BGE-M3 Q8_0 · mean usa mean pooling.*BGE-M3 Q8_0 · CLS/).waitFor();
    await superseded.getByRole('button', { name: 'Preparar índice de embeddings', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
    const upgrade = (await page.evaluate(() => window.actions)).find(action => action[0] === 'preview' && action[1].model === 'bge-m3-q8_0-cls');
    assert.equal(upgrade?.[1].provider, 'nodus');
    assert.equal(upgrade?.[1].input.kind, 'plain', 'the CLS index keeps the input recipe of the index it replaces, not the form selection');
    assert.equal(await page.getByTestId('embedding-index-b').getByTestId('embedding-index-superseded').count(), 0, 'cloud indexes show no pooling hint');
    await page.setViewportSize({ width: 640, height: 900 });
    const box = await manager.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 640);
    const artifacts = process.env.NODUS_EMBEDDING_UI_ARTIFACTS || root;
    await mkdir(artifacts, { recursive: true });
    await page.locator('main').evaluate(element => { element.scrollTop = 0; });
    await page.screenshot({ path: path.join(artifacts, 'embedding-indexes.png'), fullPage: true });
    assert.deepEqual(errors, []);
  } finally { await close(); await rm(root, { recursive: true, force: true }); }
});
