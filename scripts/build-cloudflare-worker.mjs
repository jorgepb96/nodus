import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = process.cwd();
await import('./generate-mutation-contract.mjs');
const output = path.join(root, 'cloudflare', 'dist');
const generated = path.join(root, 'cloudflare', 'src', 'generated');
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true });
fs.mkdirSync(generated, { recursive: true });
// Cloudflare turns this subdirectory into an independent repository during the
// official deploy flow, so it needs the complete license rather than a link to
// a file that only exists in the parent repository.
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(root, 'cloudflare', 'LICENSE'));

// The Deploy to Cloudflare button treats cloudflare/ as an isolated project.
// Generate the two shared, pure modules inside that project so its source tree
// never reaches into the parent monorepo at deployment time.
for (const entry of [
  { source: 'server/lib/core/debates.mjs', target: 'debates.mjs' },
  { source: 'server/lib/core/academicWorkspace.mjs', target: 'academicWorkspace.mjs' },
  { source: 'shared/deepResearchReport.ts', target: 'deepResearchReport.mjs' },
  { source: 'shared/embeddingContract.ts', target: 'embeddingContract.mjs' },
]) {
  await build({
    entryPoints: [path.join(root, entry.source)],
    outfile: path.join(generated, entry.target),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    sourcemap: false,
    legalComments: 'none',
    banner: { js: `// GENERATED by scripts/build-cloudflare-worker.mjs from ${entry.source}; do not edit.` },
  });
}
await build({
  entryPoints: [path.join(root, 'cloudflare', 'src', 'worker.mjs')],
  outfile: path.join(output, 'worker.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  sourcemap: true,
  legalComments: 'external',
  banner: { js: '/* Nodus Cloud Worker — AGPL-3.0-only; source: https://github.com/jorgepb96/nodus */' },
});
const migrationNames = fs.readdirSync(path.join(root, 'cloudflare', 'migrations')).filter((name) => /^\d{4}_[a-z0-9_-]+\.sql$/.test(name)).sort();
if (!migrationNames.length) throw new Error('Nodus Cloud needs at least one D1 migration.');
for (const name of migrationNames) fs.copyFileSync(path.join(root, 'cloudflare', 'migrations', name), path.join(output, name));
fs.writeFileSync(path.join(output, 'migrations.json'), `${JSON.stringify({ schemaVersion: 1, migrations: migrationNames }, null, 2)}\n`);
fs.copyFileSync(path.join(root, 'cloudflare', 'catalog', 'pricing.v1.json'), path.join(output, 'pricing.v1.json'));
const catalogConfig = JSON.parse(fs.readFileSync(path.join(root, 'cloudflare', 'catalog-config.json'), 'utf8'));
if (process.env.NODUS_CLOUDFLARE_CATALOG_URL) catalogConfig.catalogUrl = process.env.NODUS_CLOUDFLARE_CATALOG_URL.trim();
if (process.env.NODUS_CLOUDFLARE_CATALOG_PUBLIC_KEY) catalogConfig.ed25519PublicKeyPem = process.env.NODUS_CLOUDFLARE_CATALOG_PUBLIC_KEY.replace(/\\n/g, '\n').trim();
fs.writeFileSync(path.join(output, 'catalog-config.json'), `${JSON.stringify(catalogConfig, null, 2)}\n`);
console.log(`Nodus Cloud Worker built in ${path.relative(root, output)}`);
