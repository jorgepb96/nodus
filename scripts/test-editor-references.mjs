import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { installRuntimeHooks, repoRoot, requireElectronRuntime } from './lib/tsRuntimeHooks.mjs';
if (!requireElectronRuntime(fileURLToPath(import.meta.url), '--electron-reference-test')) process.exit(0);
const profile = await mkdtemp(path.join(os.tmpdir(), 'nodus-references-'));
installRuntimeHooks(profile);
const require = createRequire(import.meta.url);
try {
  const references = require(path.join(repoRoot, 'shared/editorReferences.ts'));
  const native = require(path.join(repoRoot, 'shared/blockNoteDocument.ts'));
  const catalog = references.editorReferenceCatalog({ ideas: Array.from({length: 200}, (_,i) => ({global_id: 'idea/'+i,label: 'Memória '+i,statement:'Paisaje'})).concat([{global_id:'hidden',label:'Oculta',orphaned_at:'now'}]), authors:[{author_id:'a 1',name:'Autor [A]'}], works:[{nodus_id:'archived',title:'Archivada',archived:1}], notes:[{id:'trashed',title:'Papelera',trashed_at:'now'}] });
  assert.equal(catalog.length,201, 'all ideas, including those beyond the first page, remain available');
  assert.equal(references.searchEditorReferences(catalog,'memoria paisaje').length,200, 'diacritics and multiple terms');
  assert.equal(references.searchEditorReferences([...catalog,...catalog],'').length,201,'deduplicate durable destinations');
  assert.deepEqual(references.parseEditorReference('nodus://idea/idea%2F199'),{kind:'idea',id:'idea/199'});
  for(const href of ['javascript:alert(1)','nodus://author/','nodus://author/%xx','nodus://idea/path/extra']) assert.equal(references.parseEditorReference(href),null);
  for (const href of ['nodus://idea/a','https://example.test','mailto:test@example.test','#section','relative/file']) assert.equal(references.editorLinkAllowed(href),true);
  for (const href of ['javascript:alert(1)','java\nscript:alert(1)','data:text/html,x','vbscript:x','nodus:']) assert.equal(references.editorLinkAllowed(href),false);
  const link = {type:'link',href:'nodus://author/a%201',content:[{type:'text',text:'Autor [A] \\ archivo',styles:{bold:true}}]};
  const document=[{id:'stable',type:'paragraph',props:{},content:[link],children:[{id:'nested',type:'paragraph',props:{},content:[link],children:[]}]}];
  const markdown=native.blockNoteToMarkdown(document);
  const roundtrip=native.markdownToBlockNote(markdown,document);
  assert.deepEqual(roundtrip[0].content[0],link,'Markdown projections round-trip brackets, slash and inline formatting');
  assert.equal(roundtrip[0].id,'stable');
  assert.equal(references.documentReferences(document).length,1,'context deduplicates links in nested blocks');
  const table=[{id:'table',type:'table',props:{},content:{rows:[{cells:[{content:[link]}]}]},children:[]}];
  assert.equal(references.documentReferences(table)[0].id,'a 1','table links remain visible in context');
  const database=require(path.join(repoRoot,'electron/db/database.ts'));
  const db=database.getDb();
  const repo=require(path.join(repoRoot,'electron/db/editorReferencesRepo.ts'));
  const settings=require(path.join(repoRoot,'electron/db/settingsRepo.ts'));
  const manual=require(path.join(repoRoot,'electron/db/manualIdeasRepo.ts'));
  settings.updateSettings({academicMode:'manual'});
  db.prepare('INSERT INTO ideas(global_id,type,label,statement) VALUES(?,?,?,?)').run('automatic-hidden','claim','Invisible en manual','No filtrar');
  const idea=manual.createManualIdea({title:'Idea manual visible',folderId:null});
  db.prepare('INSERT INTO authors(author_id,name) VALUES(?,?)').run('author-test','Autora de prueba');
  db.prepare('INSERT INTO works(nodus_id,title,year) VALUES(?,?,?)').run('work-test','Obra de prueba',2026);
  const results=repo.listEditorReferences();
  assert.ok(results.some(item=>item.id===idea.globalId&&item.kind==='idea'));
  assert.equal(results.filter(item=>item.title==='Idea manual visible').length,1,'manual idea has a single representation');
  assert.ok(!results.some(item=>item.id==='automatic-hidden'),'respect Manual visibility');
  assert.ok(results.some(item=>item.id==='author-test'));
  assert.ok(results.some(item=>item.id==='work-test'));
  db.prepare('INSERT INTO works(nodus_id,title,year,authors_json,creators_json) VALUES(?,?,?,?,?)').run('citation-work','Fuente específica',2025,JSON.stringify(['Jane Smith']),JSON.stringify([{role:'editor',firstName:'Jane',lastName:'Smith'}]));
  db.prepare('INSERT INTO works(nodus_id,title,archived) VALUES(?,?,?)').run('citation-archived','Fuente específica',1);
  const citationResults=repo.listEditorReferences({onlyWorks:true,search:'Smith 2025',limit:1});
  assert.deepEqual(citationResults.map(item=>item.id),['citation-work'],'citation picker searches creators and year without loading unrelated references');
  assert.deepEqual(citationResults[0].bibliography.creators,[{creatorType:'editor',firstName:'Jane',lastName:'Smith',name:undefined}]);
  assert.ok(repo.listEditorReferences({onlyWorks:true,limit:1}).length<=1);
  assert.equal(repo.listEditorReferences({onlyWorks:true,search:'%'}).length,0,'search wildcard characters are literal');
  assert.ok(results.every(item=>Object.keys(item).every(key=>['id','kind','title','subtitle','href','bibliography','pageLabel','physicalPage'].includes(key))),'metadata-only IPC');
  database.closeDb();
  console.log('Editor references passed: full catalogue, privacy/visibility, search, native/Markdown round-trip, nested/table context and safe routes.');
} finally { await rm(profile,{recursive:true,force:true}); }
