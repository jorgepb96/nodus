import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contract = JSON.parse(fs.readFileSync(path.join(root, 'shared', 'mutableTables.json'), 'utf8'));
const tables = Object.entries(contract.tables || {});
function writeChanged(target, content) {
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) return;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
}
if (contract.schemaVersion !== 1 || tables.length === 0) throw new Error('Invalid mutable table contract.');

for (const [table, definition] of tables) {
  if (!/^[a-z][a-z0-9_]*$/.test(table) || !Array.isArray(definition.key) || !definition.key.length) {
    throw new Error(`Invalid mutable table definition: ${table}`);
  }
  if (definition.scope !== undefined && definition.scope !== 'user') {
    throw new Error(`Invalid mutable table scope: ${table}`);
  }
}

const moduleBody = `// GENERATED by scripts/generate-mutation-contract.mjs; do not edit.\n` +
  `export const MUTABLE_TABLE_CONTRACT_VERSION = ${contract.schemaVersion};\n` +
  `export const MUTABLE_TABLES = ${JSON.stringify(contract.tables, null, 2)};\n` +
  `export const MUTABLE_TABLE_NAMES = Object.freeze(Object.keys(MUTABLE_TABLES));\n`;

for (const target of [
  path.join(root, 'server', 'lib', 'core', 'generatedMutableTables.mjs'),
  path.join(root, 'cloudflare', 'src', 'generated', 'mutableTables.mjs'),
]) {
  writeChanged(target, moduleBody);
}

const tsBody = `// GENERATED by scripts/generate-mutation-contract.mjs; do not edit.\n` +
  `export const MUTABLE_TABLES = ${JSON.stringify(tables.map(([name]) => name), null, 2)} as const;\n` +
  `export type MutableTable = (typeof MUTABLE_TABLES)[number];\n`;
writeChanged(path.join(root, 'electron', 'serverSync', 'generatedMutableTables.ts'), tsBody);

const mobileRoot = path.resolve(root, '..', 'nodus-mobile');
if (fs.existsSync(path.join(mobileRoot, 'ios', 'Packages', 'NodusKit'))) {
  const swiftAliases = {
    db_databases: 'databases',
    db_data_sources: 'databaseDataSources',
    db_columns: 'databaseColumns',
    db_rows: 'databaseRows',
    db_cells: 'databaseCells',
    db_views: 'databaseViews',
    db_view_sources: 'databaseViewSources',
    db_view_revisions: 'databaseViewRevisions',
    db_select_options: 'databaseSelectOptions',
    db_relations: 'databaseRelations',
    db_attachments: 'databaseAttachments',
    db_row_templates: 'databaseRowTemplates',
    db_template_runs: 'databaseTemplateRuns',
    db_row_hierarchy: 'databaseRowHierarchy',
    db_row_dependencies: 'databaseRowDependencies',
    db_task_configs: 'databaseTaskConfigs',
    db_sprints: 'databaseSprints',
    db_sprint_rows: 'databaseSprintRows',
  };
  const swiftCases = tables.map(([name]) => {
    const parts = name.split('_');
    const identifier = parts[0] + parts.slice(1).map((part) => part[0].toUpperCase() + part.slice(1)).join('');
    return `    case ${swiftAliases[name] || identifier} = "${name}"`;
  }).join('\n');
  const swift = `// GENERATED by ../nodus/scripts/generate-mutation-contract.mjs; do not edit.\n` +
    `public enum MutableTable: String, Sendable, Codable, CaseIterable {\n${swiftCases}\n}\n`;
  const target = path.join(mobileRoot, 'ios', 'Packages', 'NodusKit', 'Sources', 'NodusKit', 'Generated', 'MutableTable.generated.swift');
  writeChanged(target, swift);
}

console.log(`Generated ${tables.length} mutable table definitions.`);
